import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
# Load Dataset
df = pd.read_csv("placement_predict_50k Dataset.csv")
#DatasetOverview
print(df.head())
print(df.tail())
print(df.shape)
print(df.info())
print(df.describe())
